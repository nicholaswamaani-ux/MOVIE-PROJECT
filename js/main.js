    function showMainContent() {
        document.getElementById("mainContentContainer").style.display = "block";
        document.querySelectorAll(".content-page").forEach(sec => sec.classList.remove("active-page"));
    }

    function switchInfoPage(pageId) {
        document.getElementById("mainContentContainer").style.display = "none";
        document.querySelectorAll(".content-page").forEach(sec => sec.classList.remove("active-page"));
        const targetPage = document.getElementById(pageId);
        if(targetPage) {
            targetPage.classList.add("active-page");
        }
        window.scrollTo({ top: 0, behavior: 'smooth' });
    }

    // Toggle View All for individual grids
    function toggleViewAll(gridId, btn) {
        const grid = document.getElementById(gridId);
        const extraItems = grid.querySelectorAll(".extra-item");
        const isExpanded = grid.classList.toggle("expanded");

        extraItems.forEach(item => {
            item.style.display = isExpanded ? "block" : "none";
        });

        if (isExpanded) {
            btn.innerHTML = 'Show Less <i class="fa-solid fa-chevron-up"></i>';
        } else {
            btn.innerHTML = 'View All <i class="fa-solid fa-chevron-down"></i>';
        }
    }

    // Search filter across cards
    const searchInput = document.getElementById("searchInput");
    searchInput.addEventListener("input", function() {
        showMainContent();
        const term = searchInput.value.toLowerCase();
        document.querySelectorAll(".movie-card").forEach(card => {
            const title = card.querySelector("h3").textContent.toLowerCase();
            card.style.display = title.includes(term) ? "block" : "none";
        });
    });

    function switchToSignup() {
        document.getElementById("formTitle").textContent = "Sign Up";
        document.getElementById("formSubtitle").textContent = "Create an account to watch movies and live TV channels.";
        document.querySelector(".submit-btn").textContent = "Sign Up";
        document.querySelector(".signup-text").innerHTML = 'Already have an account? <span onclick="switchToLogin()">Sign in now</span>';
    }

    function switchToLogin() {
        document.getElementById("formTitle").textContent = "Sign In";
        document.getElementById("formSubtitle").textContent = "Sign in to unlock movies and watch live channels.";
        document.querySelector(".submit-btn").textContent = "Sign In";
        document.querySelector(".signup-text").innerHTML = 'New to NICFLIX? <span onclick="switchToSignup()">Sign up now</span>';
    }

    document.getElementById("loginForm").addEventListener("submit", function(e) {
        e.preventDefault();
        alert("Successfully signed in! You can now stream content.");
        closeLogin();
        this.reset();
    });
